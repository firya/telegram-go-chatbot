func TestKhaleesiTextBoundaries(t *testing.T) {
	cases := []struct{ input, want string }{
		{"", ""},
		{"iPhone Bluetooth khaleesi 30% 😀 <b>&</b>\n\t", "iPhone Bluetooth khaleesi 30% 😀 <b>&</b>\n\t"},
		{"Что? ЧТО! что — чтобы. ЧТОБЫ", "Стё? СТЁ! стё — штоби. ШТОБИ"},
		{"Холодильник ХОЛОДИЛЬНИК", "Хойодийник ХОЙОДИЙНИК"},
		{"боте ботек", "боти ботек"},
		{"нет нету", "нет нетю"}, // No cross-word cascading or forced changes.
		{"объявление, вещи!\nвозле\tзонтик", "обьявьение, веси!\nвозье\tзёнтик"},
		{"что-то", "стё-тё"},
		{"команду дом", "комяндю дом"}, // No dependence on another word's patterns.
		{"дом команду", "дом комяндю"},
	}
	for _, c := range cases {
		if got := khaleesiText(c.input); got != c.want {
			t.Errorf("khaleesiText(%q) = %q, want %q", c.input, got, c.want)
		}
	}
}
